// api-generation.ts
// Generates the client side of the contract the host serves: the types of openapi-typescript, the operations whose body or reply is not JSON (D09).

import openapiTS, { astToString, type OpenAPI3 } from 'openapi-typescript';
import type { Exchange } from '../src/api/exchange.ts';

/** The folder of the contract (written by the tests of the host, ApiContractTests) and of the files generated from it. */
export const GENERATED_FOLDER = new URL('../src/api/generated/', import.meta.url);
export const CONTRACT_FILE = 'openapi.json';
export const SCHEMA_FILE = 'schema.ts';
export const EXCHANGES_FILE = 'exchanges.ts';

const METHODS = ['get', 'put', 'post', 'patch', 'delete'] as const;
const JSON_MEDIA = 'application/json';
const BINARY_MEDIA = 'application/octet-stream';

/** The part of an OpenAPI operation that tells what its body and its replies carry. */
interface ContractOperation {
  requestBody?: { content?: Record<string, unknown> };
  responses?: Record<string, { content?: Record<string, unknown> }>;
}

interface Contract {
  paths: Record<string, Partial<Record<(typeof METHODS)[number], ContractOperation>>>;
}

export interface GeneratedApi {
  schema: string;
  exchanges: string;
}

const header = (name: string, description: string): string => `// ${name}\n// ${description}\n\n`;

/** The media types of the success replies (2xx) of an operation, the replies without content left out. */
function successMedia(operation: ContractOperation): string[] {
  return Object.entries(operation.responses ?? {})
    .filter(([status]) => status.startsWith('2'))
    .flatMap(([, response]) => Object.keys(response.content ?? {}));
}

/** What an operation exchanges that is not JSON, or null when it takes and gives JSON (or nothing). */
export function exchangeOf(operation: ContractOperation): Exchange | null {
  const media = successMedia(operation);
  const file = media.includes(JSON_MEDIA) ? undefined : media[0];
  const reply: Exchange = file === undefined ? {} : { reply: file.startsWith('text/') ? 'text' : 'blob', accept: file };
  const body = Object.keys(operation.requestBody?.content ?? {});
  const exchange: Exchange = body.includes(BINARY_MEDIA) && !body.includes(JSON_MEDIA) ? { ...reply, body: 'binary' } : reply;
  return Object.keys(exchange).length === 0 ? null : exchange;
}

/** The operations of the contract that exchange something else than JSON, keyed `METHOD /path`, in the order of the keys. */
export function exchangesOf(contract: Contract): Record<string, Exchange> {
  const entries = Object.entries(contract.paths).flatMap(([path, operations]) =>
    METHODS.flatMap((method) => {
      const operation = operations[method];
      const exchange = operation ? exchangeOf(operation) : null;
      return exchange ? [[`${method.toUpperCase()} ${path}`, exchange] as const] : [];
    }));
  return Object.fromEntries(entries.sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0)));
}

function exchangesModule(contract: Contract): string {
  const literal = (exchange: Exchange): string => `{ ${Object.entries(exchange).map(([name, value]) => `${name}: '${String(value)}'`).join(', ')} }`;
  const lines = Object.entries(exchangesOf(contract)).map(([key, exchange]) => `  '${key}': ${literal(exchange)},`);
  return header(EXCHANGES_FILE, 'Operations of the API whose reply or body is not JSON, generated from openapi.json (D09): never edited by hand.')
    + "import type { Exchange } from '../exchange.ts';\n\n"
    + '/** Keyed `METHOD /path` as the contract writes them; an operation that is not listed takes and gives JSON. */\n'
    + `export const EXCHANGES: Readonly<Record<string, Exchange>> = {\n${lines.join('\n')}\n};\n`;
}

/** The two generated files for a contract, their line ends LF. */
export async function generateApi(contract: Contract): Promise<GeneratedApi> {
  const types = astToString(await openapiTS(contract as unknown as OpenAPI3)).replace(/\r\n/g, '\n');
  return {
    schema: header(SCHEMA_FILE, 'Types of the API generated by openapi-typescript from openapi.json, the contract the host serves (D09): never edited by hand.') + types,
    exchanges: exchangesModule(contract),
  };
}
