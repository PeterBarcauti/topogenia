// laneTints.ts
// The eight lane tints of the charter (spec 9.2) and the WCAG contrast computation that keeps each ink readable.

export interface LaneTint {
  readonly key: string;
  readonly pastel: string;
  readonly ink: string;
}

/** Charter values (spec 9.2); the generated tokens may darken an ink that would miss the minimum contrast. */
export const LANE_TINTS: readonly LaneTint[] = [
  { key: 'rose', pastel: '#F9DCE6', ink: '#8A3459' },
  { key: 'lavender', pastel: '#E5E0F8', ink: '#4F3F99' },
  { key: 'sky', pastel: '#D9E9FA', ink: '#285B8C' },
  { key: 'mint', pastel: '#D5F0E3', ink: '#276A4F' },
  { key: 'peach', pastel: '#FCE3D4', ink: '#8A4424' },
  { key: 'vanilla', pastel: '#F8EFC8', ink: '#6E5A10' },
  { key: 'lilac', pastel: '#EEDDF4', ink: '#6E3D86' },
  { key: 'aqua', pastel: '#D4EEF0', ink: '#25646B' },
];

/** Minimum contrast of normal text (WCAG 2.2 AA, NF08). */
export const MIN_TEXT_CONTRAST = 4.5;

function channels(hex: string): [number, number, number] {
  const value = /^#([0-9A-Fa-f]{6})$/.exec(hex)?.[1];
  if (value === undefined) throw new Error(`Invalid colour ${hex}`);
  return [0, 2, 4].map((i) => parseInt(value.slice(i, i + 2), 16)) as [number, number, number];
}

function toHex([r, g, b]: [number, number, number]): string {
  return '#' + [r, g, b].map((c) => Math.round(c).toString(16).padStart(2, '0')).join('').toUpperCase();
}

/** Relative luminance (WCAG 2.2). */
export function luminance(hex: string): number {
  const [r, g, b] = channels(hex).map((c) => {
    const s = c / 255;
    return s <= 0.03928 ? s / 12.92 : ((s + 0.055) / 1.055) ** 2.4;
  }) as [number, number, number];
  return 0.2126 * r + 0.7152 * g + 0.0722 * b;
}

export function contrastRatio(a: string, b: string): number {
  const [light, dark] = [luminance(a), luminance(b)].sort((x, y) => y - x) as [number, number];
  return (light + 0.05) / (dark + 0.05);
}

/** Darkens the ink by steps of 2 % until it reaches the minimum contrast on the background. */
export function ensureContrast(ink: string, background: string, minimum = MIN_TEXT_CONTRAST): string {
  let rgb = channels(ink);
  let candidate = ink.toUpperCase();
  for (let step = 0; contrastRatio(candidate, background) < minimum; step++) {
    if (step > 400) throw new Error(`No darker ink of ${ink} reaches ${minimum}:1 on ${background}`);
    rgb = rgb.map((c) => c * 0.98) as [number, number, number];
    candidate = toHex(rgb);
  }
  return candidate;
}

/** Tints as written in tokens.css: the ink adjusted when needed. */
export function resolvedTints(): LaneTint[] {
  return LANE_TINTS.map((t) => ({ ...t, ink: ensureContrast(t.ink, t.pastel) }));
}

/** The generated block of tokens.css (between the markers). */
export function laneTokensBlock(): string {
  const lines = resolvedTints().flatMap((t, i) => [
    `  --lane-${i + 1}-pastel: ${t.pastel};`,
    `  --lane-${i + 1}-ink: ${t.ink};`,
  ]);
  return lines.join('\n');
}

